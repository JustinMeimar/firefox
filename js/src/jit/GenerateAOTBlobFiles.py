# Parses jit/AOTBlobSchema.yaml and emits jit/AOTBlobGenerated.h with
# manifest structs, decoded-payload views, and Encode/Decode helpers
# for every declared AOT blob kind.

import io

import buildconfig
import yaml
from mozbuild.preprocessor import Preprocessor

HEADER_TEMPLATE = """\
/* This Source Code Form is subject to the terms of the Mozilla Public
 * License, v. 2.0. If a copy of the MPL was not distributed with this
 * file, You can obtain one at http://mozilla.org/MPL/2.0/. */

#ifndef %(includeguard)s
#define %(includeguard)s

/* This file is generated by jit/GenerateAOTBlobFiles.py from
 * jit/AOTBlobSchema.yaml. Do not edit! */

%(contents)s

#endif // %(includeguard)s
"""


def load_yaml(yaml_path):
    pp = Preprocessor()
    pp.context.update(buildconfig.defines["ALLDEFINES"])
    pp.out = io.StringIO()
    pp.do_filter("substitution")
    pp.do_include(yaml_path)
    return yaml.safe_load(pp.out.getvalue())


PRIMITIVE_SIZE = {"u8": 1, "u16": 2, "u32": 4}
PRIMITIVE_CPP = {"u8": "uint8_t", "u16": "uint16_t", "u32": "uint32_t"}


def field_size(f):
    if f["type"] in PRIMITIVE_SIZE:
        return PRIMITIVE_SIZE[f["type"]]
    if f["type"] == "raw":
        return int(f["size"])
    raise ValueError(f"unknown field type: {f['type']}")


def field_align(f):
    s = field_size(f)
    return s if s in (1, 2, 4, 8) else 1


def field_cpp_type(f):
    if f["type"] in PRIMITIVE_CPP:
        return PRIMITIVE_CPP[f["type"]]
    if f["type"] == "raw":
        return f["cpp_type"]
    raise ValueError(f["type"])


def struct_sizeof(fields):
    offset = 0
    max_align = 1
    for f in fields:
        a = field_align(f)
        max_align = max(max_align, a)
        offset = (offset + a - 1) & ~(a - 1)
        offset += field_size(f)
    return (offset + max_align - 1) & ~(max_align - 1)


def emit_pod_struct(name, fields, doc=None):
    lines = []
    if doc:
        lines.append(f"// {doc}")
    lines.append(f"struct {name} {{")
    for f in fields:
        lines.append(f"  {field_cpp_type(f)} {f['name']} = {{}};")
    lines.append("};")
    size = struct_sizeof(fields)
    lines.append(f"static_assert(sizeof({name}) == {size},")
    lines.append(
        f'              "{name} sizeof drift; edit AOTBlobSchema.yaml");'
    )
    return "\n".join(lines) + "\n"


def emit_payload_struct(name, manifest_type, metadata):
    lines = [f"struct {name} {{"]
    lines.append(f"  {manifest_type} manifest;")
    lines.append("  mozilla::Span<const uint8_t> code;")
    for m in metadata:
        lines.append(f"  mozilla::Span<const {m['element']}> {m['name']};")
    lines.append("};")
    return "\n".join(lines) + "\n"


def emit_encode(kind_name, payload_type, metadata):
    lines = [
        f"[[nodiscard]] inline bool EncodeAOTBlob_{kind_name}(",
        f"    AOTBlobWriter& blob, const {payload_type}& p) {{",
        "  if (!p.code.empty() &&",
        "      !blob.writeCode(p.code.data(), p.code.size())) {",
        "    return false;",
        "  }",
        "  if (!blob.writeManifest(p.manifest)) return false;",
    ]
    for m in metadata:
        lines.append(
            f"  if (!blob.writeMetadataArray(p.{m['name']})) return false;"
        )
    lines += ["  return true;", "}"]
    return "\n".join(lines) + "\n"


def emit_decode(kind_name, manifest_type, payload_type, metadata):
    lines = [
        f"[[nodiscard]] inline bool DecodeAOTBlob_{kind_name}(",
        f"    AOTBlobReader& reader, {payload_type}* out) {{",
        f"  if (reader.entry()->manifestSize != sizeof({manifest_type})) {{",
        "    return false;",
        "  }",
        f"  out->manifest = reader.readManifest<{manifest_type}>();",
        "  out->code = reader.code();",
    ]
    for m in metadata:
        lines.append(
            f"  out->{m['name']} = reader.readMetadataArray<{m['element']}>("
            f"out->manifest.{m['count_from']});"
        )
    lines += ["  return true;", "}"]
    return "\n".join(lines) + "\n"


def emit_blob(kind_name, blob):
    manifest_type = f"AOTManifest_{kind_name}"
    payload_type = f"AOTPayload_{kind_name}"
    metadata = blob.get("metadata", [])

    out = [f"// -------- Blob: {kind_name} (kind_id={blob['kind_id']}) --------"]
    if blob.get("doc"):
        out.append(f"// {blob['doc']}")
    out.append("")
    out.append(emit_pod_struct(manifest_type, blob["manifest"]))
    out.append(emit_payload_struct(payload_type, manifest_type, metadata))
    out.append(emit_encode(kind_name, payload_type, metadata))
    out.append(emit_decode(kind_name, manifest_type, payload_type, metadata))
    return "\n".join(out)


def main(c_out, yaml_path):
    schema = load_yaml(yaml_path)

    body = [
        "#include <cstdint>",
        "",
        '#include "mozilla/Span.h"',
        "",
        '#include "jit/AOT.h"',
        '#include "jit/BaselineIC.h"',
        '#include "jit/BaselineJIT.h"',
        '#include "jit/CacheIR.h"',
        "",
        "namespace js::jit {",
        "",
    ]

    for name, s in (schema.get("structs") or {}).items():
        body.append(emit_pod_struct(name, s["fields"], s.get("doc")))

    for name, blob in (schema.get("blobs") or {}).items():
        body.append(emit_blob(name, blob))

    body.append("}  // namespace js::jit")

    HEADER_TEMPLATE_CTX = {
        "includeguard": "jit_AOTBlobGenerated_h",
        "contents": "\n".join(body),
    }
    c_out.write(HEADER_TEMPLATE % HEADER_TEMPLATE_CTX)
